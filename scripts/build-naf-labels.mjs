/* global console, fetch, URL */
// Regenerates src/catalog/naf-labels.ts from the INSEE NAF rév. 2 nomenclature as published by
// @socialgouv/codes-naf (Apache-2.0; data: INSEE, Licence Ouverte). Sub-classes only (NN.NNL), the level the
// API Recherche d'Entreprises returns in `activite_principale`. Run: node scripts/build-naf-labels.mjs
import { writeFileSync } from "node:fs";

const SOURCE = "https://raw.githubusercontent.com/SocialGouv/codes-naf/master/index.json";
const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE} responded ${res.status}`);
const all = await res.json();
const subclasses = all
  .filter((entry) => /^[0-9]{2}\.[0-9]{2}[A-Z]$/.test(entry.id) && typeof entry.label === "string" && entry.label.trim())
  .sort((a, b) => a.id.localeCompare(b.id));
if (subclasses.length < 700) throw new Error(`Only ${subclasses.length} sub-classes: refusing to write a truncated table`);

const lines = subclasses.map((entry) => `  ["${entry.id}", ${JSON.stringify(entry.label.trim())}],`);
const file = `/**
 * French labels of every NAF rév. 2 sub-class (NN.NNL), the level the API Recherche
 * d'Entreprises returns in \`activite_principale\`. The API stopped returning
 * \`libelle_activite_principale\` in 2026; {@link nafLabel} fills the gap offline.
 *
 * GENERATED by scripts/build-naf-labels.mjs from the INSEE nomenclature as published by
 * @socialgouv/codes-naf — do not edit by hand, re-run the script.
 * Data: INSEE (Licence Ouverte). ${subclasses.length} entries, generated ${new Date().toISOString().slice(0, 10)}.
 */

export const NAF_LABELS: ReadonlyMap<string, string> = new Map<string, string>([
${lines.join("\n")}
]);

/** French label of a NAF rév. 2 sub-class code ("10.71C" → "Boulangerie et boulangerie-pâtisserie"), or null. */
export function nafLabel(code: string | null | undefined): string | null {
  if (!code) return null;
  return NAF_LABELS.get(code.trim().toUpperCase()) ?? null;
}
`;
writeFileSync(new URL("../src/catalog/naf-labels.ts", import.meta.url), file);
console.log(`src/catalog/naf-labels.ts: ${subclasses.length} sub-classes`);
